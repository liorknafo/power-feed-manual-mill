"""Fabrication outputs for JLCPCB into hardware/fab/: Gerbers, Excellon drills + map, BOM (JLC columns),
CPL / placement file, a zip of Gerbers + drills, and README.md with the board specs and the list of
parts that have no LCSC number.

  python3 hardware/tools/export_fab.py        (plain python; only kicad-cli is used)
"""

import csv
import glob
import io
import os
import shutil
import subprocess
import tempfile
import zipfile

KCLI = "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.normpath(os.path.join(HERE, "..", "kicad"))
FAB = os.path.normpath(os.path.join(HERE, "..", "fab"))
PCB = os.path.join(KDIR, "power-feed.kicad_pcb")
SCH = os.path.join(KDIR, "power-feed.kicad_sch")
NAME = "power-feed"

COPPER = ["F.Cu", "In1.Cu", "In2.Cu", "B.Cu"]
OTHER = ["F.Mask", "B.Mask", "F.SilkS", "B.SilkS", "F.Paste", "B.Paste", "Edge.Cuts"]


def run(*args):
    r = subprocess.run([KCLI] + list(args), capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(" ".join(args) + "\n" + r.stdout + r.stderr)
    return r.stdout


def gerbers_and_drills(gdir):
    os.makedirs(gdir, exist_ok=True)
    for f in glob.glob(os.path.join(gdir, "*")):
        os.remove(f)
    run("pcb", "export", "gerbers", "-o", gdir, "-l", ",".join(COPPER + OTHER), "--subtract-soldermask", PCB)
    run("pcb", "export", "drill", "-o", gdir + os.sep, "--format", "excellon", "--excellon-separate-th",
        "--generate-map", "--map-format", "pdf", "--drill-origin", "absolute", PCB)
    # kicad-cli writes a job file too; keep it, JLC ignores it
    return sorted(os.listdir(gdir))


def bom(path):
    """JLCPCB BOM: Comment, Designator, Footprint, LCSC Part #. Grouped by value + footprint + LCSC."""
    tmp = os.path.join(tempfile.mkdtemp(), "bom.csv")
    run("sch", "export", "bom", "-o", tmp, "--fields", "Value,Reference,Footprint,LCSC,MPN",
        "--labels", "Comment,Designator,Footprint,LCSC,MPN", "--group-by", "Value,Footprint,LCSC",
        "--ref-range-delimiter", "", "--exclude-dnp", SCH)
    rows = list(csv.DictReader(open(tmp, newline="")))
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(["Comment", "Designator", "Footprint", "LCSC Part #", "MPN"])
    missing = []
    for r in rows:
        fp = r["Footprint"].split(":")[-1]
        w.writerow([r["Comment"], r["Designator"], fp, r["LCSC"], r["MPN"]])
        if not r["LCSC"].strip():
            missing.append((r["Comment"], fp, r["Designator"]))
    open(path, "w", newline="").write(out.getvalue())
    return rows, missing


def cpl(path, bom_rows):
    """JLCPCB CPL: Designator, Mid X, Mid Y, Layer, Rotation (mm, KiCad placement-file convention)."""
    tmp = os.path.join(tempfile.mkdtemp(), "pos.csv")
    run("pcb", "export", "pos", "-o", tmp, "--format", "csv", "--units", "mm", "--side", "both",
        "--exclude-dnp", PCB)
    refs = {ref.strip() for r in bom_rows for ref in r["Designator"].split(",")}
    n = 0
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Designator", "Mid X", "Mid Y", "Layer", "Rotation"])
        for r in csv.DictReader(open(tmp, newline="")):
            if r["Ref"] not in refs:  # mounting holes etc. (board-only, not in the BOM)
                continue
            w.writerow([r["Ref"], "%.3f" % float(r["PosX"]), "%.3f" % float(r["PosY"]),
                        "Top" if r["Side"] == "top" else "Bottom", "%.1f" % float(r["Rot"])])
            n += 1
    return n


README = """# Fabrication files — MILL POWER FEED v1 controller

Generated by `hardware/tools/export_fab.py` from `hardware/kicad/power-feed.kicad_pcb` (KiCad 9, DRC clean,
schematic parity clean).

| File | Content |
|---|---|
| `{name}-gerbers.zip` | Gerbers (4 copper, 2 mask, 2 silk, 2 paste, edge) + Excellon drills + drill map: upload this to JLCPCB |
| `gerbers/` | the same files unzipped |
| `{name}-bom.csv` | BOM, JLCPCB columns: Comment, Designator, Footprint, LCSC Part # (+ MPN) |
| `{name}-cpl.csv` | pick-and-place: Designator, Mid X, Mid Y, Layer, Rotation (mm, KiCad placement convention: Y up) |

## Board specification (order form)

- Size 100 x 100 mm, rectangular, 4 mounting holes M3.
- **4 layers**, 1.6 mm FR-4, stack-up F.Cu signal / In1 GND / In2 power (+36 V, +3V3) / B.Cu signal.
  JLCPCB standard 4-layer stack (JLC04161H-7628) is fine.
- **Outer copper 2 oz** recommended (motor phases ~3.5 A RMS); inner 0.5 oz. 1 oz works at reduced
  motor current.
- Minimum track / space **0.15 mm**, minimum via **0.5 mm / 0.25 mm drill**, minimum drill **0.2 mm**
  (TQFP-48 exposed-pad thermal vias). Hole-to-copper 0.25 mm.
- Surface finish: **HASL lead-free or ENIG** (ENIG preferred for the TQFP-48 and 0402 parts).
- Solder mask any colour; silkscreen white. Vias tented.
- Remove order number: yes (or put it under J4).
- Castellated holes: no. Impedance control: no.

## Assembly notes

- Components on the top side only. Through-hole parts: J1, J2, J3 (Phoenix MSTBA 5.08), J4 (2x7 IDC),
  J5 (JST-XH 7p), C1, C27 (470 uF radial), F1 (5x20 fuse holder) — hand solder or JLC THT assembly.
- The Raspberry Pi Pico (A1) is the SMD (castellated) variant soldered flat on the board.
- U2 (TMC5160A) exposed pad and the four CSD88537ND half-bridges need the paste layer as generated.

## Parts without an LCSC number

The schematic carries an `LCSC` field for {with_lcsc} of {total} parts ({groups_with} of {groups} BOM lines).
These BOM lines have no LCSC number yet and must be matched to a JLC basic/extended part (or sourced
separately) before ordering assembly:

| Comment | Footprint | Designators |
|---|---|---|
{missing_rows}
"""


def main():
    os.makedirs(FAB, exist_ok=True)
    gdir = os.path.join(FAB, "gerbers")
    files = gerbers_and_drills(gdir)
    zpath = os.path.join(FAB, NAME + "-gerbers.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(os.path.join(gdir, f), f)
    rows, missing = bom(os.path.join(FAB, NAME + "-bom.csv"))
    n = cpl(os.path.join(FAB, NAME + "-cpl.csv"), rows)
    total = sum(len(r["Designator"].split(",")) for r in rows)
    with_lcsc = sum(len(r["Designator"].split(",")) for r in rows if r["LCSC"].strip())
    open(os.path.join(FAB, "README.md"), "w").write(README.format(
        name=NAME, total=total, with_lcsc=with_lcsc, groups=len(rows), groups_with=len(rows) - len(missing),
        missing_rows="\n".join("| %s | %s | %s |" % m for m in missing)))
    print("gerber/drill files:", len(files))
    for f in files:
        print("   ", f)
    print("zip:", zpath)
    print("BOM lines: %d (%d parts, %d with LCSC); CPL rows: %d" % (len(rows), total, with_lcsc, n))
    print("BOM lines without LCSC: %d" % len(missing))


if __name__ == "__main__":
    main()
